const SNAPSHOT_TIMES = [0, 100, 500, 1500]; // [DEBUG-vp01]
const startTime = Date.now(); // [DEBUG-vp01]
let snapshots = []; // [DEBUG-vp01]
let probeContainer = null; // [DEBUG-vp01]
let overlayContainer = null; // [DEBUG-vp01]
let isExpanded = true; // [DEBUG-vp01]
let active = false; // [DEBUG-vp01]
let lastSnapshot = null; // [DEBUG-vp01]
// [DEBUG-vp01]
// [DEBUG-vp01] Create hidden CSS unit and safe-area probes in DOM
function createProbes() { // [DEBUG-vp01]
  if (typeof document === 'undefined') return; // [DEBUG-vp01]
  if (document.getElementById('debug-vp-probes')) return; // [DEBUG-vp01]
  probeContainer = document.createElement('div'); // [DEBUG-vp01]
  probeContainer.id = 'debug-vp-probes'; // [DEBUG-vp01]
  probeContainer.setAttribute('aria-hidden', 'true'); // [DEBUG-vp01]
  probeContainer.style.cssText = 'position:fixed;top:0;left:-9999px;width:0;height:0;pointer-events:none;visibility:hidden;z-index:-1;'; // [DEBUG-vp01]
  probeContainer.innerHTML = [ // [DEBUG-vp01]
    '<div id="debug-probe-vh" style="height:100vh;width:1px;"></div>', // [DEBUG-vp01]
    '<div id="debug-probe-dvh" style="height:100dvh;width:1px;"></div>', // [DEBUG-vp01]
    '<div id="debug-probe-svh" style="height:100svh;width:1px;"></div>', // [DEBUG-vp01]
    '<div id="debug-probe-lvh" style="height:100lvh;width:1px;"></div>', // [DEBUG-vp01]
    '<div id="debug-probe-safe" style="padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px);padding-left:env(safe-area-inset-left,0px);padding-right:env(safe-area-inset-right,0px);width:1px;"></div>', // [DEBUG-vp01]
  ].join(''); // [DEBUG-vp01]
  document.body.appendChild(probeContainer); // [DEBUG-vp01]
} // [DEBUG-vp01]
