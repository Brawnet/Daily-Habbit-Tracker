// [DEBUG-vp01] Initialize Viewport Debugger listeners & timeline
export function initViewportDebug() { // [DEBUG-vp01]
  if (typeof window === 'undefined' || typeof document === 'undefined') return; // [DEBUG-vp01]
  let hasQueryParam = false; // [DEBUG-vp01]
  try { // [DEBUG-vp01]
    const p = new URLSearchParams(window.location.search); // [DEBUG-vp01]
    hasQueryParam = p.get('debug') === 'viewport' || window.location.hash.includes('debug=viewport'); // [DEBUG-vp01]
  } catch {} // [DEBUG-vp01]
  let isStored = false; // [DEBUG-vp01]
  try { // [DEBUG-vp01]
    isStored = localStorage.getItem('debug_viewport') === '1'; // [DEBUG-vp01]
  } catch {} // [DEBUG-vp01]
  const isStandalone = (typeof navigator !== 'undefined' && navigator.standalone === true) || // [DEBUG-vp01]
    (typeof window !== 'undefined' && window.matchMedia && window.matchMedia('(display-mode: standalone)').matches); // [DEBUG-vp01]
  if (hasQueryParam) { // [DEBUG-vp01]
    try { localStorage.setItem('debug_viewport', '1'); } catch {} // [DEBUG-vp01]
  } // [DEBUG-vp01]
  // [DEBUG-vp01] Activate if query param, stored, or standalone Home Screen mode
  if (!hasQueryParam && !isStored && !isStandalone) { // [DEBUG-vp01]
    return; // [DEBUG-vp01]
  } // [DEBUG-vp01]
  active = true; // [DEBUG-vp01]
  createProbes(); // [DEBUG-vp01]
  // [DEBUG-vp01] Initial launch snapshots at 0, 100, 500, 1500 ms
  SNAPSHOT_TIMES.forEach(ms => { // [DEBUG-vp01]
    setTimeout(() => { // [DEBUG-vp01]
      recordSnapshot(`launch:${ms}ms`); // [DEBUG-vp01]
    }, ms); // [DEBUG-vp01]
  }); // [DEBUG-vp01]
  // [DEBUG-vp01] Input focus & blur listeners
  document.addEventListener('focusin', (e) => { // [DEBUG-vp01]
    const target = e.target; // [DEBUG-vp01]
    if (target && (target.tagName === 'INPUT' || target.tagName === 'TEXTAREA' || target.getAttribute('role') === 'textbox')) { // [DEBUG-vp01]
      recordSnapshot(`focus:${target.id || target.name || target.tagName}`); // [DEBUG-vp01]
    } // [DEBUG-vp01]
  }, { passive: true }); // [DEBUG-vp01]
  document.addEventListener('focusout', (e) => { // [DEBUG-vp01]
    const target = e.target; // [DEBUG-vp01]
    if (target && (target.tagName === 'INPUT' || target.tagName === 'TEXTAREA' || target.getAttribute('role') === 'textbox')) { // [DEBUG-vp01]
      recordSnapshot(`blur:${target.id || target.name || target.tagName}`); // [DEBUG-vp01]
      setTimeout(() => { // [DEBUG-vp01]
        recordSnapshot(`blur+300ms:${target.id || target.name || target.tagName}`); // [DEBUG-vp01]
      }, 300); // [DEBUG-vp01]
    } // [DEBUG-vp01]
  }, { passive: true }); // [DEBUG-vp01]
  // [DEBUG-vp01] Rotation and resize listeners
  window.addEventListener('resize', () => { // [DEBUG-vp01]
    recordSnapshot('window-resize'); // [DEBUG-vp01]
  }, { passive: true }); // [DEBUG-vp01]
  window.addEventListener('orientationchange', () => { // [DEBUG-vp01]
    setTimeout(() => recordSnapshot('orientationchange+100ms'), 100); // [DEBUG-vp01]
    setTimeout(() => recordSnapshot('orientationchange+500ms'), 500); // [DEBUG-vp01]
  }, { passive: true }); // [DEBUG-vp01]
  if (window.visualViewport) { // [DEBUG-vp01]
    window.visualViewport.addEventListener('resize', () => { // [DEBUG-vp01]
      recordSnapshot('visualViewport-resize'); // [DEBUG-vp01]
    }, { passive: true }); // [DEBUG-vp01]
  } // [DEBUG-vp01]
} // [DEBUG-vp01]
