// [DEBUG-vp01] Pure measurement collector
export function measureViewport() { // [DEBUG-vp01]
  if (typeof window === 'undefined' || typeof document === 'undefined') { // [DEBUG-vp01]
    return null; // [DEBUG-vp01]
  } // [DEBUG-vp01]
  createProbes(); // [DEBUG-vp01]
  const winH = window.innerHeight || 0; // [DEBUG-vp01]
  const winW = window.innerWidth || 0; // [DEBUG-vp01]
  const vv = window.visualViewport; // [DEBUG-vp01]
  const vvH = vv ? vv.height : winH; // [DEBUG-vp01]
  const vvW = vv ? vv.width : winW; // [DEBUG-vp01]
  const vvTop = vv ? vv.offsetTop : 0; // [DEBUG-vp01]
  const vvScale = vv ? vv.scale : 1; // [DEBUG-vp01]
  const screenH = (window.screen && window.screen.height) || 0; // [DEBUG-vp01]
  const screenW = (window.screen && window.screen.width) || 0; // [DEBUG-vp01]
  const availH = (window.screen && window.screen.availHeight) || 0; // [DEBUG-vp01]
  const dpr = window.devicePixelRatio || 1; // [DEBUG-vp01]
  const probeVh = document.getElementById('debug-probe-vh'); // [DEBUG-vp01]
  const probeDvh = document.getElementById('debug-probe-dvh'); // [DEBUG-vp01]
  const probeSvh = document.getElementById('debug-probe-svh'); // [DEBUG-vp01]
  const probeLvh = document.getElementById('debug-probe-lvh'); // [DEBUG-vp01]
  const probeSafe = document.getElementById('debug-probe-safe'); // [DEBUG-vp01]
  const vh = probeVh ? probeVh.getBoundingClientRect().height : 0; // [DEBUG-vp01]
  const dvh = probeDvh ? probeDvh.getBoundingClientRect().height : 0; // [DEBUG-vp01]
  const svh = probeSvh ? probeSvh.getBoundingClientRect().height : 0; // [DEBUG-vp01]
  const lvh = probeLvh ? probeLvh.getBoundingClientRect().height : 0; // [DEBUG-vp01]
  let safeTop = 0, safeBottom = 0, safeLeft = 0, safeRight = 0; // [DEBUG-vp01]
  if (probeSafe) { // [DEBUG-vp01]
    const cs = window.getComputedStyle(probeSafe); // [DEBUG-vp01]
    safeTop = parseFloat(cs.paddingTop) || 0; // [DEBUG-vp01]
    safeBottom = parseFloat(cs.paddingBottom) || 0; // [DEBUG-vp01]
    safeLeft = parseFloat(cs.paddingLeft) || 0; // [DEBUG-vp01]
    safeRight = parseFloat(cs.paddingRight) || 0; // [DEBUG-vp01]
  } // [DEBUG-vp01]
  const rootAppH = window.getComputedStyle(document.documentElement).getPropertyValue('--app-height').trim(); // [DEBUG-vp01]
  const appEl = document.getElementById('app'); // [DEBUG-vp01]
  const appRect = appEl ? appEl.getBoundingClientRect() : null; // [DEBUG-vp01]
  const navEl = document.getElementById('bottom-nav'); // [DEBUG-vp01]
  const navRect = navEl ? navEl.getBoundingClientRect() : null; // [DEBUG-vp01]
  const tabContentEl = document.getElementById('tab-content'); // [DEBUG-vp01]
  const tabContentRect = tabContentEl ? tabContentEl.getBoundingClientRect() : null; // [DEBUG-vp01]
  const isStandalone = (typeof navigator !== 'undefined' && navigator.standalone === true) || // [DEBUG-vp01]
    (typeof window !== 'undefined' && window.matchMedia && window.matchMedia('(display-mode: standalone)').matches); // [DEBUG-vp01]
  const isPortrait = winH >= winW; // [DEBUG-vp01]
  const orientation = (window.screen && window.screen.orientation && window.screen.orientation.type) || // [DEBUG-vp01]
    (typeof window.orientation !== 'undefined' ? `${window.orientation}°` : (isPortrait ? 'portrait' : 'landscape')); // [DEBUG-vp01]
  const ua = navigator.userAgent || ''; // [DEBUG-vp01]
  const iosMatch = ua.match(/OS (\d+[_\.]\d+)/); // [DEBUG-vp01]
  const iosVer = iosMatch ? `iOS ${iosMatch[1].replace(/_/g, '.')}` : (ua.includes('iPhone') ? 'iOS iPhone' : 'Other OS'); // [DEBUG-vp01]
  const visibleLimit = vv ? (vvTop + vvH) : winH; // [DEBUG-vp01]
  const navBottom = navRect ? navRect.bottom : 0; // [DEBUG-vp01]
  const delta = Math.round((navBottom - Math.min(winH, visibleLimit)) * 10) / 10; // [DEBUG-vp01]
  const isGreen = delta <= 0.5; // [DEBUG-vp01]
  return { // [DEBUG-vp01]
    timestamp: Date.now(), // [DEBUG-vp01]
    winH, winW, vvH, vvW, vvTop, vvScale, // [DEBUG-vp01]
    screenH, screenW, availH, dpr, // [DEBUG-vp01]
    vh, dvh, svh, lvh, rootAppH, // [DEBUG-vp01]
    safeTop, safeBottom, safeLeft, safeRight, // [DEBUG-vp01]
    appRect: appRect ? { top: Math.round(appRect.top * 10) / 10, bottom: Math.round(appRect.bottom * 10) / 10, height: Math.round(appRect.height * 10) / 10 } : null, // [DEBUG-vp01]
    navRect: navRect ? { top: Math.round(navRect.top * 10) / 10, bottom: Math.round(navRect.bottom * 10) / 10, height: Math.round(navRect.height * 10) / 10 } : null, // [DEBUG-vp01]
    tabContentRect: tabContentRect ? { top: Math.round(tabContentRect.top * 10) / 10, bottom: Math.round(tabContentRect.bottom * 10) / 10, height: Math.round(tabContentRect.height * 10) / 10 } : null, // [DEBUG-vp01]
    isStandalone: !!isStandalone, // [DEBUG-vp01]
    orientation, // [DEBUG-vp01]
    isPortrait, // [DEBUG-vp01]
    iosVer, // [DEBUG-vp01]
    navBottom, // [DEBUG-vp01]
    visibleLimit, // [DEBUG-vp01]
    delta, // [DEBUG-vp01]
    isGreen, // [DEBUG-vp01]
  }; // [DEBUG-vp01]
} // [DEBUG-vp01]
