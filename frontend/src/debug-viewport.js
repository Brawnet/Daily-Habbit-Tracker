// [DEBUG-vp01] Toggle debug overlay visibility on demand // [DEBUG-vp01]
export function toggleViewportDebug() { // [DEBUG-vp01]
  if (!active) { // [DEBUG-vp01]
    active = true; // [DEBUG-vp01]
    isExpanded = true; // [DEBUG-vp01]
    createProbes(); // [DEBUG-vp01]
    recordSnapshot('manual-toggle-on'); // [DEBUG-vp01]
  } else { // [DEBUG-vp01]
    isExpanded = !isExpanded; // [DEBUG-vp01]
    renderOverlay(); // [DEBUG-vp01]
  } // [DEBUG-vp01]
} // [DEBUG-vp01]
// [DEBUG-vp01]
// [DEBUG-vp01] Expose toggle helper on window for devtools / console // [DEBUG-vp01]
if (typeof window !== 'undefined') { // [DEBUG-vp01]
  window.__toggleViewportDebug = toggleViewportDebug; // [DEBUG-vp01]
  let headerTapCount = 0; // [DEBUG-vp01]
  let headerTapTimer = null; // [DEBUG-vp01]
  document.addEventListener('click', (e) => { // [DEBUG-vp01]
    const target = e.target; // [DEBUG-vp01]
    if (target && target.closest && target.closest('header')) { // [DEBUG-vp01]
      headerTapCount++; // [DEBUG-vp01]
      clearTimeout(headerTapTimer); // [DEBUG-vp01]
      headerTapTimer = setTimeout(() => { headerTapCount = 0; }, 600); // [DEBUG-vp01]
      if (headerTapCount >= 3) { // [DEBUG-vp01]
        headerTapCount = 0; // [DEBUG-vp01]
        toggleViewportDebug(); // [DEBUG-vp01]
      } // [DEBUG-vp01]
    } // [DEBUG-vp01]
  }); // [DEBUG-vp01]
} // [DEBUG-vp01]
