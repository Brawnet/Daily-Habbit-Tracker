// [DEBUG-vp01] Record event milestone snapshot
export function recordSnapshot(label) { // [DEBUG-vp01]
  const data = measureViewport(); // [DEBUG-vp01]
  if (!data) return null; // [DEBUG-vp01]
  const entry = { // [DEBUG-vp01]
    id: snapshots.length + 1, // [DEBUG-vp01]
    label, // [DEBUG-vp01]
    timeMs: Date.now() - startTime, // [DEBUG-vp01]
    data, // [DEBUG-vp01]
  }; // [DEBUG-vp01]
  snapshots.push(entry); // [DEBUG-vp01]
  lastSnapshot = data; // [DEBUG-vp01]
  renderOverlay(); // [DEBUG-vp01]
  return entry; // [DEBUG-vp01]
} // [DEBUG-vp01]
